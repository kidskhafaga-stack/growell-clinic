def _screen_doctor(appt, patient_id):
    """Whose work is being collected for — and the doctor the share is owed to.

    Three sources, in the order they are trustworthy: the appointment, the form
    (the screen resolved it on the way in and carries it back), and finally the
    patient's own unbilled work.

    The form matters more than it looks. Without it the POST re-derives the
    doctor from what is *still* unbilled — and by then the very dose or
    procedure that named them is being billed by this request, so the answer
    can come back ``None`` and the invoice is saved with no doctor and no
    commission. The screen showed a name and the record kept nobody.

    The last source is what the retired invoice builder did on its way in, and
    dropping it would have quietly stopped paying doctors for work reception
    collects without an appointment.
    """
    if appt:
        return appt.doctor_id
    from_form = request.form.get("doctor_id", type=int)
    if from_form:
        return from_form
    doctor_id = _vaccine_doctor(patient_id)
    if doctor_id is None:
        for vs in _unbilled_patient_services(patient_id):
            if vs.visit and vs.visit.doctor_id:
                return vs.visit.doctor_id
    return doctor_id


def _checkout_screen(appt, patient):
    """Reception checkout: show the charges with editable prices, let the user
    add services, pick a named discount, and collect with one or several
    payment methods — then print. Replaces the silent one-click collect so the
    amount is always visible before payment."""
    patient = patient or (appt.patient if appt else None)
    if patient is None:
        abort(404)
    patient_id = patient.id
    doctor_id = _screen_doctor(appt, patient_id)
    lang = getattr(g, "lang", "ar")

    if request.method == "POST":
        # One invoice per visit-day: append to today's invoice when it exists
        # (exam collected first, then a procedure/vaccine added later) instead
        # of raising a new invoice for every collection step.
        invoice = _todays_invoice(patient_id)
        if invoice is None:
            invoice = Invoice(invoice_number=generate_invoice_number(),
                              patient_id=patient_id, doctor_id=doctor_id,
                              created_by=current_user.id)
            db.session.add(invoice)
            db.session.flush()
        elif invoice.doctor_id is None:
            invoice.doctor_id = doctor_id

        descs = request.form.getlist("line_desc")
        sids = request.form.getlist("line_service_id")
        prices = request.form.getlist("line_price")
        qtys = request.form.getlist("line_qty")
        nocomms = request.form.getlist("line_no_commission")
        brands = request.form.getlist("line_brand_id")
        dose_numbers = request.form.getlist("line_dose_number")
        new_items = []          # only these burn consumables (see below)
        kept = []               # which submitted lines became real charges
        for i, desc in enumerate(descs):
            desc = (desc or "").strip()
            try:
                price = float(prices[i]) if i < len(prices) and prices[i] != "" else 0
            except (TypeError, ValueError):
                price = 0
            qty = 1
            try:
                qty = int(qtys[i]) if i < len(qtys) and qtys[i] else 1
            except (TypeError, ValueError):
                qty = 1
            if not desc or price <= 0:
                continue
            sid = None
            try:
                sid = int(sids[i]) if i < len(sids) and sids[i] else None
            except (TypeError, ValueError):
                sid = None
            item = InvoiceItem(service_id=sid, description=desc,
                               unit_price=round(price, 2), quantity=max(qty, 1))
            # Remember which vaccine this line paid for, so a dose the doctor
            # later refuses or swaps can be settled against it.
            try:
                item.vaccine_brand_id = (int(brands[i])
                                         if i < len(brands) and brands[i] else None)
            except (TypeError, ValueError):
                item.vaccine_brand_id = None
            try:
                item.vaccine_dose_number = (
                    int(dose_numbers[i])
                    if i < len(dose_numbers) and dose_numbers[i] else None)
            except (TypeError, ValueError):
                item.vaccine_dose_number = None
            svc = db.session.get(Service, sid) if sid else None
            # Vaccine product lines carry no invoice commission (doctor share is
            # the brand's doctor_fee, tracked on the dose — never double-paid).
            no_comm = i < len(nocomms) and nocomms[i] in ("1", "on", "true")
            if svc is not None and not no_comm:
                item.commission_amount = svc.doctor_share(item.net, invoice.doctor)
            invoice.items.append(item)
            new_items.append(item)
            kept.append(i)

        # Consumables: a billed service burns store items (a spirometry burns a
        # mouthpiece and a filter). This used to happen only when a line was
        # added to an existing invoice, so the main checkout never deducted
        # anything. Deducted once, here, as the invoice is raised.
        db.session.flush()
        burned = 0
        for item in new_items:
            if item.service_id is None:
                continue
            burned += _deduct_service_consumables(item, invoice)

        # Mark as billed exactly what these lines charged for (never twice, and
        # never something the cashier took off the bill).
        # Which unbilled procedures this checkout could have charged for:
        # the appointment's visit when there is one, otherwise everything of
        # this patient's that is still unbilled — the same set the screen was
        # filled from, or a line the cashier kept would never be marked.
        billable = (_unbilled_visit_services(appt) if appt
                    else _unbilled_patient_services(patient_id))
        _mark_billed(invoice,
                     _uncharged_vaccines(patient_id),
                     billable,
                     _claimed_ids("line_dose_id", kept),
                     _claimed_ids("line_vs_id", kept))

        if not invoice.items:
            db.session.rollback()
            flash(t("cashier.nothing_to_collect"), "warning")
            return redirect(_checkout_url(appt, patient_id))

        disc, auto = _chosen_discount()
        if disc is not None:
            _apply_named_discount(invoice, disc)
        _apply_coverage(invoice, patient, auto_discount=auto)
        invoice.recalc_status()

        # Split payment: parallel amount[]/method[] (collect now); may be empty
        # (collect later — leaves an open balance the cashier can settle).
        # Every payment is clamped to the remaining balance so the invoice can
        # never be overpaid (no more negative balances from double submits).
        amounts = request.form.getlist("amount")
        methods = request.form.getlist("method")
        tills = request.form.getlist("account_id")
        # Shift gate: cash going into the drawer needs an open shift ("pay
        # later" doesn't, and neither does money that never touches it).
        paying = [m for a, m in zip(amounts, methods)
                  if (a or "").strip() not in ("", "0", "0.0")]
        if paying and _shift_gate_blocked(paying):
            db.session.rollback()
            flash(t("shifts.gate_blocked"), "warning")
            return redirect(url_for("finance.cashier"))
        shift_id = _current_shift_id()
        remaining = invoice.balance
        change_total = 0.0
        for i, (amt_raw, m) in enumerate(zip(amounts, methods)):
            _, remaining, change = _take_payment(
                invoice, amt_raw, m, remaining, shift_id,
                account_id=_int_at(tills, i))
            change_total = round(change_total + change, 2)
        _till_notice(paying)
        invoice.recalc_status()
        ActivityLog.record("invoice.checkout", user_id=current_user.id, entity="invoice",
                           detail=invoice.invoice_number, ip_address=client_ip())
        db.session.commit()
        _post_journal_safe("invoice", invoice)
        flash(t("invoices.created"), "success")
        if burned:
            flash(t("services.consumables_deducted", n=burned), "info")
        _flash_change(change_total)
        return redirect(url_for("finance.invoice_receipt", invoice_id=invoice.id, auto=1))

    lines = (_checkout_lines(appt, lang) if appt
             else _patient_checkout_lines(patient, doctor_id, lang))
    suggested, suggested_amount = _discount_preview(patient, doctor_id, lines)
    # The doctor is already settled by the time anybody reaches the till, so
    # this splits on the server — unlike booking, where the doctor is being
    # chosen in the same form and the browser has to do it.
    from app.utils.doctor_services import split as _split_services
    _services = (Service.query.filter_by(is_active=True)
                 .order_by(Service.name).all())
    _my_services, _other_services = _split_services(
        db.session.get(User, doctor_id) if doctor_id else None, _services)
    from app.utils.vaccine_sale import as_json, sellable
    return render_template(
        "finance/checkout.html", appt=appt, patient=patient, lines=lines,
        post_url=_checkout_url(appt, patient_id),
        doctor=db.session.get(User, doctor_id) if doctor_id else None,
        # The picker belongs here, on the path reception actually walks. It
        # went onto the invoice builder first, which is the screen this change
        # exists to keep them off.
        vaccine_offers_json=as_json(sellable(patient, lang)),
        vaccine_fee=_vaccine_service(),
        # Said before the work, not after it: the gate used to fire on submit,
        # throw the whole form away and redirect — with a family at the desk.
        shift_needed=_shift_gate_blocked(),
        # Money can come back out on the same screen it went in on. It used to
        # live only on the invoice view, which reception reaches by knowing an
        # invoice number.
        refundable=_refundable(patient_id),
        refund_needs_approval=(Setting.get("refund_approval_required", "1") != "0"
                               and not current_user.is_admin),
        services=_services,
        my_services=_my_services, other_services=_other_services,
        discounts=NamedDiscount.query.filter_by(is_active=True).order_by(NamedDiscount.name).all(),
        suggested=suggested, suggested_amount=suggested_amount,
        payment_methods=PAYMENT_METHODS,
    )


def _refundable(patient_id, days=30):
    """This patient's recent invoices that money can actually come back out of.

    Refunding lived only on the invoice *view* screen, which reception reaches
    by knowing an invoice number — so the one thing a family asks for at the
    desk ("we paid for a vaccine we're not taking") sent the cashier hunting
    through a list. It belongs where the money was taken.

    Only invoices with something collected on them are offered: refunding an
    unpaid invoice is not a refund, it is a discount, and it has its own way in.
    """
    since = date.today() - timedelta(days=days)
    recent = (Invoice.query
              .filter(Invoice.patient_id == patient_id,
                      Invoice.invoice_date >= since)
              .order_by(Invoice.id.desc()).limit(20).all())
    return [inv for inv in recent if inv.paid > 0][:5]


def _discount_preview(patient, doctor_id, lines):
    """What the automatic pick *would* be for these draft lines → (disc, amount).

    The invoice doesn't exist yet on the checkout screen, but the cashier needs
    to see the discount before taking the money — not discover it on the
    printed receipt. The draft lines are priced through the same chooser, so
    what is shown is what will be applied."""
    from types import SimpleNamespace

    if patient is None or not lines:
        return None, 0
    items = []
    for line in lines:
        sid = str(line.get("service_id") or "")
        svc = db.session.get(Service, int(sid)) if sid.isdigit() else None
        try:
            gross = (float(line.get("unit_price") or 0)
                     * float(line.get("quantity") or 1))
        except (TypeError, ValueError):
            gross = 0
        items.append(SimpleNamespace(service=svc, gross=round(gross, 2),
                                     discount_value=0))
    draft = SimpleNamespace(invoice_date=date.today(), doctor_id=doctor_id,
                            items=items)
    best = _best_discount(draft, patient, doctor_id)
    return best, (_discount_worth(draft, best) if best is not None else 0)


def _chosen_discount():
    """Reception's pick on the submitted form → ``(discount, allow_auto)``.

    Three answers, not two. Blank means "work it out for me" — the system
    applies the biggest rule the patient qualifies for. ``none`` means the
    cashier looked and decided this bill carries no discount. An id is the
    cashier overruling the automatic pick, and it is honoured as chosen: they
    are standing in front of the family and we are not."""
    raw = (request.form.get("discount_id") or "").strip()
    if raw == "none":
        return None, False
    if raw.isdigit():
        disc = db.session.get(NamedDiscount, int(raw))
        if disc is not None and disc.is_active:
            return disc, False
    return None, True


def _apply_named_discount(invoice, disc):
    """Apply a named discount to lines that have no discount yet — and, when
    the discount is aimed at a category (كشف / جهاز / تطعيم…) or at one named
    service, only to those lines, so a "vaccination discount" never touches
    the exam line. One named discount per invoice: a line that already carries
    a reduction (manual, coverage, or an earlier rule) is left alone."""
    invoice.discount_id = disc.id
    invoice.discount_name = disc.display_name()
    for item in invoice.items:
        amount = _line_discount_amount(item, disc)
        if amount > 0:
            item.discount_value = amount
            item.discount_is_percent = False
            if item.service is not None:
                item.commission_amount = item.service.doctor_share(item.net, invoice.doctor)


