@finance_bp.route("/tills/move", methods=["POST"])
@capability_required("treasury_move")
def till_move():
    """Bank a drawer, draw from a till, transfer, or settle a card account.

    Behind its own capability: taking money from patients and moving the
    clinic's own money are different jobs, and whoever does the first is not
    automatically trusted with the second.
    """
    from app.models import CashAccount
    from app.utils import treasury

    def picked(field):
        # A deposit has no target, so the field is genuinely absent — asking
        # the session for row `None` is a different question from "no target".
        chosen = request.form.get(field, type=int)
        return db.session.get(CashAccount, chosen) if chosen else None

    kind = (request.form.get("kind") or "").strip()
    src = picked("account_id")
    dst = picked("to_account_id")
    # Only the source is checked. Money *arriving* somewhere you cannot work is
    # the normal case — banking your own drawer into a safe you have no access
    # to is exactly what the control is for.
    if src is not None and not src.may_be_used_by(current_user):
        abort(403, description=t("tills.not_your_till"))
    moved_on = parse_date_or_today(request.form.get("moved_on"))
    if _period_blocked(moved_on):
        return redirect(url_for("finance.tills"))
    try:
        treasury.record_movement(
            kind, src, request.form.get("amount", type=float),
            to_account=dst, fee=request.form.get("fee", type=float),
            moved_on=moved_on,
            reference=(request.form.get("reference") or "").strip() or None,
            notes=(request.form.get("notes") or "").strip() or None,
            user_id=current_user.id)
    except treasury.MovementError as exc:
        flash(t(f"tills.err_{exc}"), "danger")
        return redirect(url_for("finance.tills"))
    ActivityLog.record("till.move", user_id=current_user.id, entity="till",
                       entity_id=src.id if src else None,
                       detail=f"{kind}:{request.form.get('amount')}",
                       ip_address=client_ip())
    db.session.commit()
    flash(t("tills.moved"), "success")
    return redirect(url_for("finance.tills"))


# ------------------------------------------------ bank reconciliation ------
def _reconcilable_or_404(account_id):
    """A till there is an external record to check against.

    Behind ``treasury_move`` at the route, and narrowed here to the tills a
    statement can exist for. A cash drawer is excluded on purpose: it has a
    count, which is a different screen and a different act — somebody's hand in
    the drawer, not a file from a bank.
    """
    from app.models import CashAccount
    from app.utils.bank_import import RECONCILABLE_KINDS

    account = db.get_or_404(CashAccount, account_id)
    if account.kind not in RECONCILABLE_KINDS:
        abort(404)
    if not (_sees_all_tills() or account.may_be_used_by(current_user)):
        abort(403, description=t("tills.not_your_till"))
    return account


