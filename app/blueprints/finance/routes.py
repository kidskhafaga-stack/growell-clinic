def _uncollected_by_patient(days=7):
    """Money that silently falls through the till: vaccine doses given (and
    priced) but never invoiced + doctor-added visit services with no invoice —
    typically because the visit was collected *before* the doctor added them.
    Grouped per patient so the cashier can chase each one with one click."""
    from datetime import timedelta

    from app.models import VisitService

    since = date.today() - timedelta(days=days)
    lang = getattr(g, "lang", "ar")
    out = {}

    def bucket(patient):
        return out.setdefault(patient.id, {"patient": patient, "items": [],
                                           "total": 0.0})

    doses = (PatientVaccine.query.filter(
        PatientVaccine.event_type == "given",
        PatientVaccine.given_outside.is_(False),
        PatientVaccine.invoice_id.is_(None),
        PatientVaccine.given_date >= since).all())
    for d in doses:
        b = d.brand
        if not (b and (b.price or 0) > 0 and d.patient):
            continue
        e = bucket(d.patient)
        name = b.vaccine.display_name(lang) if b.vaccine else d.vaccine.display_name(lang)
        e["items"].append(f"{name} — {b.display_name(lang)}")
        e["total"] = round(e["total"] + (b.price or 0), 2)

    svcs = (VisitService.query.join(Visit, VisitService.visit_id == Visit.id)
            .filter(VisitService.invoice_id.is_(None),
                    Visit.visit_date >= since).all())
    for vs in svcs:
        visit = vs.visit
        if visit is None or visit.patient is None:
            continue
        price = vs.service.price_for(visit.doctor) if vs.service else 0
        if (price or 0) <= 0:
            continue
        e = bucket(visit.patient)
        e["items"].append(vs.name)
        e["total"] = round(e["total"] + price * (vs.quantity or 1), 2)

    return sorted(out.values(), key=lambda e: -e["total"])


def _drawer_summary(on_date):
    """The day's drawer figures (shared by the cashier screen and its print)."""
    from collections import Counter

    start = datetime.combine(on_date, datetime.min.time())
    end = datetime.combine(on_date, datetime.max.time())
    pays = Payment.query.filter(Payment.paid_at >= start, Payment.paid_at <= end).all()
    by_method = Counter()
    refunds = 0.0
    cash_in = cash_out = 0.0
    for p in pays:
        amt = p.amount or 0
        if p.kind == "refund":
            refunds += amt
            if p.method == "cash":
                cash_out += amt
        else:
            by_method[p.method] += amt
            if p.method == "cash":
                cash_in += amt
    drawer = CashDrawerDay.query.filter_by(drawer_date=on_date).first()
    opening_float = drawer.opening_float if drawer else 0
    cash_collected = round(cash_in - cash_out, 2)
    # Only the day's total is wanted from these, and that total is summed in
    # Python from each invoice's lines — so the lines come along rather than
    # one query per invoice raised today.
    from sqlalchemy.orm import selectinload

    todays = (Invoice.query
              .options(selectinload(Invoice.items))
              .filter(Invoice.invoice_date == on_date).all())
    day_shifts = (CashierShift.query
                  .filter(CashierShift.opened_at >= start,
                          CashierShift.opened_at <= end)
                  .order_by(CashierShift.opened_at).all())
    return {
        "drawer": drawer,
        "opening_float": opening_float,
        "by_method": dict(by_method),
        "collected": round(sum(by_method.values()), 2),
        "refunds": round(refunds, 2),
        "cash_collected": cash_collected,
        "expected_cash": round(opening_float + cash_collected, 2),
        "billed_today": round(sum(i.total for i in todays), 2),
        "day_shifts": day_shifts,
    }


