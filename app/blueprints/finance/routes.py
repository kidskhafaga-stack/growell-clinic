def _siblings_seen_today(patient, on_date=None, doctor_id=None):
    """How many children of this family the clinic saw on ``on_date``.

    "Seen" is deliberately generous: a sibling counts once they have an
    appointment that wasn't cancelled, a visit, or an invoice that day — the
    discount is about the family's trip to the clinic, not about who happened
    to be invoiced first.

    Pass ``doctor_id`` to count only the children that doctor saw: "الأخوين
    سوا" is one doctor's offer on their own list, so two children who saw two
    different doctors on the same day are two separate visits, not a pair."""
    from app.models import Appointment

    if patient is None or not patient.family_id:
        return 0
    day = on_date or date.today()
    ids = {p.id for p in Patient.query.filter_by(family_id=patient.family_id).all()}
    if not ids:
        return 0
    seen = {patient.id}
    appts = Appointment.query.filter(
        Appointment.patient_id.in_(ids), Appointment.appt_date == day,
        Appointment.status.notin_(("cancelled", "no_show")))
    visits = Visit.query.filter(Visit.patient_id.in_(ids), Visit.visit_date == day)
    invoices = Invoice.query.filter(Invoice.patient_id.in_(ids),
                                    Invoice.invoice_date == day)
    if doctor_id:
        appts = appts.filter(Appointment.doctor_id == doctor_id)
        visits = visits.filter(Visit.doctor_id == doctor_id)
        invoices = invoices.filter(Invoice.doctor_id == doctor_id)
    for query in (appts, visits, invoices):
        for row in query.all():
            seen.add(row.patient_id)
    return len(seen)


def _sibling_rule_met(disc, patient, on_date=None, doctor_id=None):
    """Whether enough siblings came together for this family rule to fire."""
    if patient is None or not patient.family_id:
        return False
    count = _siblings_seen_today(patient, on_date,
                                 doctor_id if disc.same_doctor else None)
    return count >= max(disc.min_siblings or 2, 2)


def _line_discount_amount(item, disc):
    """What ``disc`` would take off one invoice line — capped by the service.

    Returns 0 for a line the rule doesn't reach, or one that already carries a
    discount: nothing is ever stacked on top of an existing reduction."""
    if (item.discount_value or 0) > 0:
        return 0
    if not disc.applies_to_line(item.service):
        return 0
    amount = disc.amount_for(item.gross)
    service = item.service
    if service is not None and service.max_discount:
        amount = min(amount, round(item.gross * service.max_discount / 100.0, 2))
    return max(amount, 0)


def _discount_worth(invoice, disc):
    """What this rule is actually worth on *this* invoice, in money.

    Comparing rules by their headline percentage is the wrong question: 50% of
    a 100 EGP exam is less than 20% of a 900 EGP bill, and a rule aimed at one
    service may be worth nothing here at all. "The bigger discount" has to mean
    the bigger number on the patient's own bill, so every candidate is priced
    against the real lines before they are compared."""
    return round(sum(_line_discount_amount(i, disc) for i in invoice.items), 2)


def _auto_candidates(invoice, patient, doctor_id=None):
    """Every named discount this invoice legitimately qualifies for."""
    from app.models import NamedDiscount

    on_date = invoice.invoice_date or date.today()
    if doctor_id is None:
        doctor_id = invoice.doctor_id
    out = []
    for disc in NamedDiscount.query.filter(NamedDiscount.is_active.is_(True)).all():
        if disc.dtype == "special" or not disc.auto_apply:
            continue                      # chosen by hand only
        if not disc.applies_to(patient, doctor_id, on_date):
            continue
        if disc.dtype == "sibling" and not _sibling_rule_met(
                disc, patient, on_date, doctor_id):
            continue
        out.append(disc)
    return out


def _best_discount(invoice, patient, doctor_id=None):
    """The single largest discount the patient qualifies for — or None.

    A child can be entitled to several at once: his club gives members 20% and
    he came with his brother for 50%. He gets one of them — the bigger one —
    never both, and reception can still overrule the pick."""
    scored = [(_discount_worth(invoice, d), d.id, d)
              for d in _auto_candidates(invoice, patient, doctor_id)]
    scored = [row for row in scored if row[0] > 0]
    if not scored:
        return None
    scored.sort(key=lambda row: (row[0], row[1]))
    return scored[-1][2]


def _auto_apply_best(invoice, patient, doctor_id=None):
    """Pick and apply the biggest discount, and say which one it was."""
    if invoice.discount_id is not None:
        return None                        # reception already chose
    best = _best_discount(invoice, patient, doctor_id)
    if best is None:
        return None
    _apply_named_discount(invoice, best)
    flash(t("discounts.auto_applied")
          .replace("{name}", best.display_name(getattr(g, "lang", "ar"))),
          "info")
    return best


def _apply_cash_prices(invoice):
    """Reprice the lines from the clinic's cash price list (التسعيرة النقدية).

    The cash agreement needs no membership card — it is what the walk-in
    patient pays — so it is applied to every invoice with no payer. Lines the
    user priced by hand (a manual discount) are left alone."""
    from app.utils.pricing import cash_tariff

    for item in invoice.items:
        if not item.service_id or (item.discount_value or 0) > 0:
            continue
        price = cash_tariff(item.service, invoice.invoice_date)
        if price is None or price == item.unit_price:
            continue
        item.unit_price = price
        if item.service is not None:
            item.commission_amount = item.service.doctor_share(item.net,
                                                               invoice.doctor)


def _apply_coverage(invoice, patient, auto_discount=True):
    """Auto-apply a member's per-service coverage to the invoice lines.

    For each covered line the entity's share becomes the line discount (so the
    patient pays the rest and the entity share is claimable). Uncovered
    services are left untouched (patient pays full — option ب). An expired card
    is not applied automatically; the user is warned instead.

    Afterwards the best named discount the patient qualifies for is applied to
    whatever is still undiscounted — unless reception already picked one, or
    asked for none (``auto_discount=False``).
    """
    coverage = patient.active_coverage if patient else None
    # If the card exists but is expired/inactive, warn and skip auto-apply.
    if coverage is None:
        expired = [c for c in getattr(patient, "coverages", []) if not c.is_valid]
        if expired:
            flash(t("coverage.expired_warn"), "warning")
        # No payer → the clinic's own cash price list applies, automatically.
        # It is not a third party that pays, so no payer is stamped on the
        # invoice and nothing becomes claimable — it only sets the price.
        _apply_cash_prices(invoice)
        if auto_discount:
            _auto_apply_best(invoice, patient)
        return

    payer = coverage.payer
    invoice.payer_id = payer.id
    invoice.coverage_card = coverage.membership_number
    invoice.coverage_expiry = coverage.expiry_date

    # If the entity works by contracts, one must be in force on the invoice date.
    if payer.contracts and payer.active_contract(invoice.invoice_date) is None:
        flash(t("contracts.none_active_warn"), "warning")
        return

    for item in invoice.items:
        if not item.service_id or (item.discount_value or 0) > 0:
            continue  # keep manual discounts; skip free-text lines
        # Contract tariff (سعر تعاقدي): members are billed at the contract's
        # negotiated price for the service, then coverage splits it.
        tariff = payer.tariff(item.service, invoice.invoice_date)
        if tariff is not None:
            item.unit_price = tariff
        covered = payer.covers(item.service, item.gross, invoice.invoice_date)
        if covered > 0:
            item.discount_value = covered
            item.discount_is_percent = False
            if item.service is not None:
                item.commission_amount = item.service.doctor_share(item.net, invoice.doctor)

    # A club whose agreement is "members pay 15% less" carries no price list,
    # so nothing above touched the invoice — its member discount lands here.
    # Same for the family offer. Whichever is worth more wins, and only on the
    # lines the coverage didn't already reduce.
    if auto_discount:
        _auto_apply_best(invoice, patient)


def _uncharged_vaccines(patient_id, days=2):
    """Recently-given, priced, not-yet-billed doses for a patient (charge on exit)."""
    from datetime import timedelta

    since = date.today() - timedelta(days=days)
    doses = (PatientVaccine.query.filter(
        PatientVaccine.patient_id == patient_id,
        PatientVaccine.event_type == "given",
        PatientVaccine.given_outside.is_(False),
        PatientVaccine.invoice_id.is_(None),
        PatientVaccine.given_date >= since).all())
    return [d for d in doses if d.brand and (d.brand.price or 0) > 0]


def _vaccine_service():
    """The coded vaccination service every vaccine line is billed under, so a
    dose reads as a real "تطعيم" service (selectable in the dropdown) instead of
    free text. Self-heals: if the clinic never seeded a vaccination-fee service
    (e.g. the wizard's vaccination capability was left unticked) one is created
    now, editable afterwards like any other service."""
    svc = service_for_visit_type("vaccination")
    if svc is not None:
        return svc
    svc = (Service.query.filter_by(code="SVC-VACFEE").first()
           or Service.query.filter_by(category="vaccination_fee",
                                       is_active=True).first())
    if svc is None:
        svc = Service(code="SVC-VACFEE", name="رسم تطعيم",
                      name_en="Vaccination fee", price=0,
                      category="vaccination_fee", commission_type="none",
                      commission_value=0, is_active=True)
        db.session.add(svc)
        db.session.flush()
        # Point the vaccination visit type at it too, if that map slot is empty.
        vt_map = visit_type_service_map()
        if "vaccination" not in vt_map:
            vt_map["vaccination"] = svc.id
            save_visit_type_service_map(vt_map)
    return svc


def _vaccine_prefill_lines(patient_id, doctor, lang, has_vacc_base):
    """Prefill lines for a patient's uncharged vaccine doses.

    Each dose bills as the vaccination *service* (not free text): one line for
    the vaccine itself at the brand price — its doctor share is the brand's
    ``doctor_fee`` tracked on the dose, so this line carries **no** invoice
    commission (``no_commission``) to avoid double-crediting the doctor. On top,
    the administration fee (رسم تطعيم) is added once, priced per the giving
    doctor (free when their price override is 0) — unless the invoice already
    carries a vaccination-visit base charge, which *is* that fee."""
    doses = _uncharged_vaccines(patient_id)
    if not doses:
        return []
    vac_svc = _vaccine_service()
    sid = str(vac_svc.id) if vac_svc else ""
    lines = []
    # Charge the administration fee at most once: not if the visit base already
    # is it, and not if today's invoice already carries a vaccination-fee line
    # (e.g. the exam was collected first and we're now collecting a leftover dose).
    inv_today = _todays_invoice(patient_id)
    already_fee = bool(inv_today) and any(
        it.service and it.service.category == "vaccination_fee"
        for it in inv_today.items)
    admin_added = has_vacc_base or already_fee
    for dose in doses:
        b = dose.brand
        name = (b.vaccine.display_name(lang) if b.vaccine
                else dose.vaccine.display_name(lang))
        lines.append({
            "service_id": sid,
            "description": name + " — " + b.display_name(lang),
            "unit_price": b.price or 0,
            "quantity": 1,
            "no_commission": "1",
            "dose_id": dose.id,
            "brand_id": b.id,
        })
        if not admin_added and vac_svc is not None:
            fee = vac_svc.price_for(dose.doctor or doctor)
            if fee and fee > 0:
                lines.append({
                    "service_id": sid,
                    "description": t("vaccinations.admin_fee_line"),
                    "unit_price": fee,
                    "quantity": 1,
                })
                admin_added = True
    return lines


def _vaccine_doctor(patient_id):
    """The doctor to credit/preselect when collecting a patient's uncharged
    doses — the doctor who actually gave the (first) dose."""
    for dose in _uncharged_vaccines(patient_id):
        if dose.doctor_id:
            return dose.doctor_id
    return None


def _todays_invoice(patient_id):
    """The patient's invoice for today, if any — the visit's ONE bill.

    Exam, in-clinic procedures and vaccines all land on the same invoice
    (appended as the day unfolds) instead of spawning a new invoice per
    collection step, so the patient's statement stays clean and accounting
    correct."""
    return (Invoice.query
            .filter(Invoice.patient_id == patient_id,
                    Invoice.invoice_date == date.today())
            .order_by(Invoice.id.desc()).first())


def _unbilled_patient_services(patient_id, days=7):
    """Recent doctor-added visit services of this patient not yet invoiced —
    across visits, because a dose/procedure added after the visit was already
    collected would otherwise never reach a bill."""
    from datetime import timedelta

    from app.models import VisitService

    since = date.today() - timedelta(days=days)
    return (VisitService.query.join(Visit, VisitService.visit_id == Visit.id)
            .filter(Visit.patient_id == patient_id,
                    VisitService.invoice_id.is_(None),
                    Visit.visit_date >= since)
            .all())


def _claimed_ids(field, kept_indexes):
    """The ids the surviving invoice lines say they are paying for.

    Each prefilled line carries the id of the thing it charges for — the dose,
    the procedure. Only the lines that actually became invoice items count, so
    a line the cashier deleted claims nothing.
    """
    values = request.form.getlist(field)
    out = set()
    for idx in kept_indexes:
        raw = values[idx] if idx < len(values) else ""
        if not raw:
            continue
        try:
            out.add(int(raw))
        except (TypeError, ValueError):
            continue
    return out


def _mark_billed(invoice, doses, services, dose_ids, service_ids):
    """Stamp only what this invoice actually charged for.

    Both collection screens used to stamp *everything* recent and unbilled,
    on the assumption that whatever was prefilled was also collected. Delete
    the vaccine line and collect the exam only, and the dose was still marked
    paid: it dropped off the "not billed yet" list, and a 900-pound vial left
    the clinic with nothing anywhere recording that it was owed.

    Now a dose or a procedure is billed when a line pays for it, not because
    it happened this week. Anything else keeps showing up at the desk — which
    is the safe direction to be wrong in: an extra prompt costs a second, a
    silent write-off costs the price of the vial.
    """
    unclaimed = []
    for dose in doses:
        if dose.id in dose_ids:
            dose.invoice_id = invoice.id
        else:
            unclaimed.append(dose)
    # A line that named the brand but not the dose — typed by hand at the desk,
    # or submitted by an older form — still pays for one dose of that brand.
    for brand_id in [it.vaccine_brand_id for it in invoice.items
                     if it.vaccine_brand_id]:
        match = next((d for d in unclaimed if d.brand_id == brand_id), None)
        if match is not None:
            match.invoice_id = invoice.id
            unclaimed.remove(match)

    for vs in services:
        if vs.id in service_ids:
            vs.invoice_id = invoice.id


