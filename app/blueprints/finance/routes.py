def _apply_coverage(invoice, patient):
    """Auto-apply a member's per-service coverage to the invoice lines.

    For each covered line the entity's share becomes the line discount (so the
    patient pays the rest and the entity share is claimable). Uncovered
    services are left untouched (patient pays full — option ب). An expired card
    is not applied automatically; the user is warned instead.
    """
    coverage = patient.active_coverage if patient else None
    # If the card exists but is expired/inactive, warn and skip auto-apply.
    if coverage is None:
        expired = [c for c in getattr(patient, "coverages", []) if not c.is_valid]
        if expired:
            flash(t("coverage.expired_warn"), "warning")
        return

    payer = coverage.payer
    invoice.payer_id = payer.id
    invoice.coverage_card = coverage.membership_number
    invoice.coverage_expiry = coverage.expiry_date

    # If the entity works by contracts, one must be in force on the invoice date.
    if payer.contracts and payer.active_contract(invoice.invoice_date) is None:
        flash(t("contracts.none_active_warn"), "warning")
        return

    for item in invoice.items:
        if not item.service_id or (item.discount_value or 0) > 0:
            continue  # keep manual discounts; skip free-text lines
        # Contract tariff (سعر تعاقدي): members are billed at the contract's
        # negotiated price for the service, then coverage splits it.
        tariff = payer.tariff(item.service, invoice.invoice_date)
        if tariff is not None:
            item.unit_price = tariff
        covered = payer.covers(item.service, item.gross, invoice.invoice_date)
        if covered > 0:
            item.discount_value = covered
            item.discount_is_percent = False
            if item.service is not None:
                item.commission_amount = item.service.doctor_share(item.net, invoice.doctor)


def _uncharged_vaccines(patient_id, days=2):
    """Recently-given, priced, not-yet-billed doses for a patient (charge on exit)."""
    from datetime import timedelta

    since = date.today() - timedelta(days=days)
    doses = (PatientVaccine.query.filter(
        PatientVaccine.patient_id == patient_id,
        PatientVaccine.event_type == "given",
        PatientVaccine.given_outside.is_(False),
        PatientVaccine.invoice_id.is_(None),
        PatientVaccine.given_date >= since).all())
    return [d for d in doses if d.brand and (d.brand.price or 0) > 0]


def _vaccine_service():
    """The coded vaccination service every vaccine line is billed under, so a
    dose reads as a real "تطعيم" service (selectable in the dropdown) instead of
    free text. Self-heals: if the clinic never seeded a vaccination-fee service
    (e.g. the wizard's vaccination capability was left unticked) one is created
    now, editable afterwards like any other service."""
    svc = service_for_visit_type("vaccination")
    if svc is not None:
        return svc
    svc = (Service.query.filter_by(code="SVC-VACFEE").first()
           or Service.query.filter_by(category="vaccination_fee",
                                       is_active=True).first())
    if svc is None:
        svc = Service(code="SVC-VACFEE", name="رسم تطعيم",
                      name_en="Vaccination fee", price=0,
                      category="vaccination_fee", commission_type="none",
                      commission_value=0, is_active=True)
        db.session.add(svc)
        db.session.flush()
        # Point the vaccination visit type at it too, if that map slot is empty.
        vt_map = visit_type_service_map()
        if "vaccination" not in vt_map:
            vt_map["vaccination"] = svc.id
            save_visit_type_service_map(vt_map)
    return svc


def _vaccine_prefill_lines(patient_id, doctor, lang, has_vacc_base):
    """Prefill lines for a patient's uncharged vaccine doses.

    Each dose bills as the vaccination *service* (not free text): one line for
    the vaccine itself at the brand price — its doctor share is the brand's
    ``doctor_fee`` tracked on the dose, so this line carries **no** invoice
    commission (``no_commission``) to avoid double-crediting the doctor. On top,
    the administration fee (رسم تطعيم) is added once, priced per the giving
    doctor (free when their price override is 0) — unless the invoice already
    carries a vaccination-visit base charge, which *is* that fee."""
    doses = _uncharged_vaccines(patient_id)
    if not doses:
        return []
    vac_svc = _vaccine_service()
    sid = str(vac_svc.id) if vac_svc else ""
    lines = []
    # Charge the administration fee at most once: not if the visit base already
    # is it, and not if today's invoice already carries a vaccination-fee line
    # (e.g. the exam was collected first and we're now collecting a leftover dose).
    inv_today = _todays_invoice(patient_id)
    already_fee = bool(inv_today) and any(
        it.service and it.service.category == "vaccination_fee"
        for it in inv_today.items)
    admin_added = has_vacc_base or already_fee
    for dose in doses:
        b = dose.brand
        name = (b.vaccine.display_name(lang) if b.vaccine
                else dose.vaccine.display_name(lang))
        lines.append({
            "service_id": sid,
            "description": name + " — " + b.display_name(lang),
            "unit_price": b.price or 0,
            "quantity": 1,
            "no_commission": "1",
            "dose_id": dose.id,
        })
        if not admin_added and vac_svc is not None:
            fee = vac_svc.price_for(dose.doctor or doctor)
            if fee and fee > 0:
                lines.append({
                    "service_id": sid,
                    "description": t("vaccinations.admin_fee_line"),
                    "unit_price": fee,
                    "quantity": 1,
                })
                admin_added = True
    return lines


def _vaccine_doctor(patient_id):
    """The doctor to credit/preselect when collecting a patient's uncharged
    doses — the doctor who actually gave the (first) dose."""
    for dose in _uncharged_vaccines(patient_id):
        if dose.doctor_id:
            return dose.doctor_id
    return None


def _todays_invoice(patient_id):
    """The patient's invoice for today, if any — the visit's ONE bill.

    Exam, in-clinic procedures and vaccines all land on the same invoice
    (appended as the day unfolds) instead of spawning a new invoice per
    collection step, so the patient's statement stays clean and accounting
    correct."""
    return (Invoice.query
            .filter(Invoice.patient_id == patient_id,
                    Invoice.invoice_date == date.today())
            .order_by(Invoice.id.desc()).first())


def _unbilled_patient_services(patient_id, days=7):
    """Recent doctor-added visit services of this patient not yet invoiced —
    across visits, because a dose/procedure added after the visit was already
    collected would otherwise never reach a bill."""
    from datetime import timedelta

    from app.models import VisitService

    since = date.today() - timedelta(days=days)
    return (VisitService.query.join(Visit, VisitService.visit_id == Visit.id)
            .filter(Visit.patient_id == patient_id,
                    VisitService.invoice_id.is_(None),
                    Visit.visit_date >= since)
            .all())


