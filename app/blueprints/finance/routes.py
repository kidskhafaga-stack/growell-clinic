@finance_bp.route("/periods", methods=["GET", "POST"])
@module_required(MODULE)
def periods():
    """The books: which periods are open and which are closed.

    Four granularities, because clinics hand over at different rhythms — the
    month, the quarter, the half, the full year. Closing any of them is an
    admin's decision and it is what makes a printed report permanent: money can
    no longer be written inside it."""
    from flask import abort

    from app.models import AccountingPeriod
    from app.utils.periods import (KINDS, close_period, count_periods,
                                   generate_periods, reopen_period,
                                   selectable_years, valid_year)

    # Typed, not picked from a closed list. The suggestions cover the years a
    # clinic wants nine times out of ten; a clinic entering 2019's books, or
    # opening 2030, was previously told no by a dropdown with nothing on the
    # screen explaining why.
    year = valid_year(request.values.get("year"))
    if request.method == "POST":
        action = (request.form.get("action") or "").strip()
        if action == "generate":
            kind = (request.form.get("kind") or "month").strip()
            if kind not in KINDS:
                kind = "month"
            before = count_periods(year, kind)
            made = generate_periods(year, kind, getattr(g, "lang", "ar"))
            db.session.commit()
            if made:
                flash(t("periods.generated").replace("{n}", str(made)), "success")
            else:
                # Creating is idempotent, so pressing twice is harmless — but
                # "0 created" reported as success reads as a failure nobody can
                # explain. Say which year and which kind already exist.
                flash(t("periods.already_there")
                      .replace("{n}", str(before))
                      .replace("{y}", str(year)), "warning")
            return redirect(url_for("finance.periods", year=year))
        if not current_user.is_admin:
            abort(403)          # closing/reopening the books is admin-only
        period = db.session.get(AccountingPeriod,
                                request.form.get("period_id", type=int))
        if period is None:
            flash(t("common.not_found"), "danger")
            return redirect(url_for("finance.periods", year=year))
        if action == "close":
            close_period(period, current_user.id)
            ActivityLog.record("period.close", user_id=current_user.id,
                               entity="accounting_period", entity_id=period.id,
                               detail=period.name, ip_address=client_ip())
            flash(t("periods.closed_ok").replace("{name}", period.name), "success")
        elif action == "reopen":
            reopen_period(period, current_user.id)
            ActivityLog.record("period.reopen", user_id=current_user.id,
                               entity="accounting_period", entity_id=period.id,
                               detail=period.name, ip_address=client_ip())
            flash(t("periods.reopened_ok").replace("{name}", period.name), "warning")
        db.session.commit()
        return redirect(url_for("finance.periods", year=year))

    query = (AccountingPeriod.query
             .filter(db.extract("year", AccountingPeriod.start_date) == year))
    # Filters, because a year now holds up to nineteen periods across four
    # granularities and an accountant looking for "the closed quarters" should
    # not be reading a wall.
    kind = (request.args.get("kind") or "").strip()
    if kind in KINDS:
        query = query.filter(AccountingPeriod.kind == kind)
    status = (request.args.get("status") or "").strip()
    if status in ("open", "closed"):
        query = query.filter(AccountingPeriod.status == status)
    needle = (request.args.get("q") or "").strip()
    if needle:
        query = query.filter(AccountingPeriod.name.ilike(f"%{needle}%"))
    rows = query.order_by(AccountingPeriod.start_date,
                          AccountingPeriod.end_date).all()
    totals = {}
    for p in rows:
        invoices = Invoice.query.filter(
            Invoice.invoice_date >= p.start_date,
            Invoice.invoice_date <= p.end_date).all()
        totals[p.id] = {
            "billed": round(sum(i.total for i in invoices), 2),
            "collected": round(sum(i.paid for i in invoices), 2),
            "count": len(invoices),
        }
    return render_template("finance/periods.html", periods=rows, year=year,
                           years=selectable_years(), totals=totals, kinds=KINDS,
                           f_kind=kind, f_status=status, f_q=needle)


