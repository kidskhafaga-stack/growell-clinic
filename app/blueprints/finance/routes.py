@finance_bp.route("/journal/new", methods=["POST"])
@module_required(MODULE)
def journal_entry_new():
    """Post a manual, balanced journal entry (adjustments, opening balances,
    depreciation…). Admin-only — this is the one place a human writes to the
    ledger, so it validates that debits equal credits before posting."""
    from flask import abort

    from app.models import Account
    from app.utils.accounting import ensure_seeded, post_entry

    if not current_user.is_admin:
        abort(403)
    ensure_seeded()

    memo = (request.form.get("memo") or "").strip()
    raw_date = (request.form.get("entry_date") or "").strip()
    try:
        entry_date = datetime.strptime(raw_date, "%Y-%m-%d").date() if raw_date else date.today()
    except ValueError:
        entry_date = date.today()
    if _period_blocked(entry_date):
        return redirect(url_for("finance.journal"))

    # Parallel arrays: account code, debit, credit per row.
    codes = request.form.getlist("line_account")
    debits = request.form.getlist("line_debit")
    credits = request.form.getlist("line_credit")
    lines = []
    total_d = total_c = 0.0
    for i, code in enumerate(codes):
        code = (code or "").strip()
        if not code:
            continue
        try:
            d = float(debits[i] or 0) if i < len(debits) else 0.0
            c = float(credits[i] or 0) if i < len(credits) else 0.0
        except ValueError:
            d = c = 0.0
        if d <= 0 and c <= 0:
            continue
        lines.append((code, round(d, 2), round(c, 2), memo))
        total_d += d
        total_c += c

    if len(lines) < 2:
        flash(t("manual_je.need_lines"), "danger")
        return redirect(url_for("finance.journal"))
    if abs(round(total_d - total_c, 2)) > 0.01:
        flash(t("manual_je.unbalanced"), "danger")
        return redirect(url_for("finance.journal"))

    try:
        entry = post_entry("manual", None, memo or t("manual_je.default_memo"),
                           lines, entry_date=entry_date, user_id=current_user.id)
    except ValueError:
        flash(t("manual_je.unbalanced"), "danger")
        return redirect(url_for("finance.journal"))
    if entry is None:
        flash(t("manual_je.failed"), "danger")
        return redirect(url_for("finance.journal"))

    ActivityLog.record("journal.manual", user_id=current_user.id,
                       entity="journal_entry", detail=entry.entry_number,
                       ip_address=client_ip())
    db.session.commit()
    flash(t("manual_je.posted").replace("{n}", entry.entry_number), "success")
    return redirect(url_for("finance.journal"))


def _post_journal_safe(kind, obj):
    """Best-effort automatic journal posting (F2) — a bookkeeping hiccup must
    never block billing, so every failure is swallowed after a rollback."""
    try:
        from app.utils import accounting as acct

        if kind == "invoice":
            acct.post_invoice(obj, user_id=current_user.id)
            for p in obj.payments:
                acct.post_payment(p, user_id=current_user.id)
            # COGS for consumables issued with this invoice (W3).
            iss = getattr(obj, "_iss_doc", None)
            if iss is not None:
                acct.post_store_doc(iss, user_id=current_user.id)
        elif kind == "payment":
            acct.post_payment(obj, user_id=current_user.id)
        elif kind == "expense":
            acct.post_expense(obj, user_id=current_user.id)
    except Exception:  # noqa: BLE001
        db.session.rollback()


def _doctors():
    """Every doctor a per-service commission can be set for, active or not.

    Inactive ones stay in: a rate that vanished when somebody was deactivated
    would silently stop being the rate their historical invoices were priced
    at. Same "who is a doctor" rule as everywhere else — role-typed *or*
    flagged as a practitioner — otherwise the commission screen would offer a
    different set of people from the one collecting the money.
    """
    return (User.query
            .filter(db.or_(User.role == "doctor",
                           User.is_practitioner.is_(True)))
            .order_by(User.full_name).all())


def _clean_commission():
    """Read & sanitise commission type/value from the request form."""
    ctype = (request.form.get("commission_type") or "none").strip()
    if ctype not in COMMISSION_TYPES:
        ctype = "none"
    cval = request.form.get("commission_value", type=float) or 0
    return ctype, cval


# Service Engine workflow flags read off the edit/add form.
_SERVICE_FLAGS = [
    "needs_doctor", "needs_device", "needs_report", "needs_consumables",
    "needs_booking", "needs_approval", "can_standalone", "can_add_during_visit",
]


def _apply_visit_type_charge(svc):
    """Assign (or clear) the visit type this service is the base charge for.

    Only when the form actually carries the field, so the smaller edit forms
    elsewhere cannot clear it by not mentioning it — the way the workflow flags
    are guarded above, and for the same reason.
    """
    if "visit_type" not in request.form:
        return
    from app.utils.pricing import set_visit_type_service
    from app.utils.visit_types import valid_key

    key = (request.form.get("visit_type") or "").strip()
    if key and valid_key(key):
        set_visit_type_service(key, svc)
    elif not key and svc.visit_type:
        set_visit_type_service(svc.visit_type, None)


def _apply_service_engine_fields(svc):
    """Read the Service Engine fields (type / cost / duration / flags) off the
    form onto ``svc``. Flags are only applied when the form marks itself as
    Service-Engine-aware (``se=1``) so the simple edit popover doesn't wipe them."""
    from app.utils.service_types import valid_key
    stype = (request.form.get("service_type") or "").strip()
    if valid_key(stype):
        svc.service_type = stype
    svc.cost = request.form.get("cost", type=float)
    svc.duration_minutes = request.form.get("duration_minutes", type=int)
    svc.device_id = request.form.get("device_id", type=int) or None
    if request.form.get("se") == "1":
        for flag in _SERVICE_FLAGS:
            setattr(svc, flag, bool(request.form.get(flag)))


