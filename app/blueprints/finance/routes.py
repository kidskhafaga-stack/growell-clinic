@finance_bp.route("/invoices/<int:invoice_id>/payment", methods=["POST"])
@cashier_access
def invoice_payment(invoice_id):
    invoice = db.get_or_404(Invoice, invoice_id)
    # One invoice can be settled with several methods at once (e.g. 500 cash +
    # 1000 card + 500 instapay). The form submits parallel amount[]/method[]
    # lists; a single quick-pay is just a one-element list.
    # A closed accounting period is a harder rule than the shift gate, so it
    # is checked first — the cashier gets the real reason, not "open a shift".
    if _period_blocked(invoice.invoice_date):
        return redirect(url_for("finance.invoice_view", invoice_id=invoice.id))
    amounts = request.form.getlist("amount")
    methods = request.form.getlist("method")
    tills = request.form.getlist("account_id")
    # Shift gate: cash only enters the drawer inside an open shift. Other
    # methods never touch it, so refusing them here would be refusing money
    # for no reason.
    if _shift_gate_blocked([m for a, m in zip(amounts, methods)
                            if (a or "").strip() not in ("", "0", "0.0")]):
        flash(t("shifts.gate_blocked"), "warning")
        return redirect(url_for("finance.cashier"))
    notes = (request.form.get("notes") or "").strip() or None
    added = 0.0
    new_payments = []
    shift_id = _current_shift_id()
    # Never accept more than the open balance: a double click or a stale form
    # can otherwise pay the same invoice twice (negative balance).
    remaining = invoice.balance
    if remaining <= 0:
        flash(t("invoices.already_settled"), "warning")
        return redirect(url_for("finance.cashier")
                        if (request.form.get("next") or "") == "cashier"
                        else url_for("finance.invoice_view", invoice_id=invoice.id))
    change_total = 0.0
    for i, (amt_raw, m) in enumerate(zip(amounts, methods)):
        pay, remaining, change = _take_payment(
            invoice, amt_raw, m, remaining, shift_id, notes=notes,
            account_id=_int_at(tills, i))
        change_total = round(change_total + change, 2)
        if pay is not None:
            new_payments.append(pay)
            added += pay.amount
    if added <= 0:
        flash(t("invoices.bad_amount"), "danger")
        return redirect(url_for("finance.invoice_view", invoice_id=invoice.id))
    invoice.recalc_status()
    ActivityLog.record("invoice.payment", user_id=current_user.id, entity="invoice",
                       detail=f"{invoice.invoice_number}:{round(added, 2)}",
                       ip_address=client_ip())
    db.session.commit()
    for pay in new_payments:
        _post_journal_safe("payment", pay)
    flash(t("invoices.payment_added"), "success")
    _till_notice([p.method for p in new_payments])
    _flash_change(change_total)
    if (request.form.get("next") or "") == "cashier":
        return redirect(url_for("finance.cashier"))
    return redirect(url_for("finance.invoice_view", invoice_id=invoice.id))


@finance_bp.route("/invoices/<int:invoice_id>/refund", methods=["POST"])
@module_required(MODULE)
def invoice_refund(invoice_id):
    """Return money to the patient (e.g. an exam re-billed as a consultation)
    and reconcile the cashier drawer."""
    from app.models import RefundRequest, Setting

    invoice = db.get_or_404(Invoice, invoice_id)
    amount = request.form.get("amount", type=float)
    if not amount or amount <= 0:
        flash(t("invoices.bad_amount"), "danger")
        return redirect(url_for("finance.invoice_view", invoice_id=invoice.id))
    if _period_blocked(invoice.invoice_date):
        return redirect(url_for("finance.invoice_view", invoice_id=invoice.id))

    # F4 approval workflow: unless the setting is off, only admins refund
    # directly — everyone else files a request a manager must approve.
    needs_approval = (Setting.get("refund_approval_required", "1") != "0"
                      and not current_user.is_admin)
    if needs_approval:
        method = (request.form.get("method") or "cash").strip()
        db.session.add(RefundRequest(
            invoice_id=invoice.id, amount=round(min(amount, invoice.paid), 2),
            method=method if method in PAYMENT_METHODS else "cash",
            reason=(request.form.get("notes") or "").strip() or None,
            requested_by=current_user.id))
        ActivityLog.record("refund.request", user_id=current_user.id,
                           entity="invoice", detail=invoice.invoice_number,
                           ip_address=client_ip())
        db.session.commit()
        flash(t("refunds.request_sent"), "info")
        if (request.form.get("next") or "") == "cashier":
            return redirect(url_for("finance.cashier"))
        return redirect(url_for("finance.invoice_view", invoice_id=invoice.id))
    if amount > invoice.paid:  # can't refund more than was actually collected
        amount = invoice.paid
    method = (request.form.get("method") or "cash").strip()
    refund_pay = Payment(
        amount=round(amount, 2), kind="refund",
        method=method if method in PAYMENT_METHODS else "cash",
        received_by=current_user.id, shift_id=_current_shift_id(),
        notes=(request.form.get("notes") or "").strip() or None,
    )
    invoice.payments.append(refund_pay)
    invoice.recalc_status()
    ActivityLog.record("invoice.refund", user_id=current_user.id, entity="invoice",
                       detail=f"{invoice.invoice_number}:-{amount}", ip_address=client_ip())
    db.session.commit()
    _post_journal_safe("payment", refund_pay)
    flash(t("invoices.refund_added"), "success")
    if (request.form.get("next") or "") == "cashier":
        return redirect(url_for("finance.cashier"))
    return redirect(url_for("finance.invoice_view", invoice_id=invoice.id))


