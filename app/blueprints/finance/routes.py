def _add_item_from_form(invoice, prefix=""):
    """Build an InvoiceItem from form fields; returns it or None if empty."""
    service_id = request.form.get(f"{prefix}service_id", type=int)
    desc = (request.form.get(f"{prefix}description") or "").strip()
    price = request.form.get(f"{prefix}unit_price", type=float)
    service = db.session.get(Service, service_id) if service_id else None

    if service and not desc:
        desc = service.name
    if service and price is None:
        price = service.price
    if not desc or price is None:
        return None

    qty = request.form.get(f"{prefix}quantity", type=int) or 1
    disc_val = request.form.get(f"{prefix}discount_value", type=float) or 0
    disc_pct = bool(request.form.get(f"{prefix}discount_is_percent"))

    item = InvoiceItem(
        service_id=service.id if service else None,
        description=desc, unit_price=price, quantity=qty,
        discount_value=disc_val, discount_is_percent=disc_pct,
    )
    # Snapshot the doctor commission for this line's net amount.
    if service is not None:
        item.commission_amount = service.doctor_share(item.net, invoice.doctor)
    return item


def _deduct_service_consumables(item, invoice):
    """Post 'out' stock movements for the consumables a billed service burns
    (qty × line quantity). Returns the number of items deducted.

    All deductions of one invoice share one numbered issue document (ISS),
    opened lazily and cached on the invoice object."""
    from app.models import StockMovement
    from app.utils.store_docs import open_document
    service = item.service if item.service_id else None
    if service is None or not service.consumables:
        return 0
    line_qty = item.quantity or 1
    n = 0
    for cons in service.consumables:
        take = (cons.quantity or 1) * line_qty
        if take <= 0 or cons.store_item_id is None:
            continue
        doc = getattr(invoice, "_iss_doc", None)
        if doc is None:
            doc = open_document("issue", reference=invoice.invoice_number)
            invoice._iss_doc = doc
        from app.utils.costing import issue_unit_cost
        db.session.add(StockMovement(
            item_id=cons.store_item_id, kind="out", qty=-abs(take),
            reason=t("services.consumed_by", svc=service.display_name(getattr(g, "lang", "ar"))),
            # COGS follows the store's dispensing policy (FIFO/LIFO layers).
            unit_cost=(issue_unit_cost(cons.item) if cons.item else None),
            created_by=current_user.id, document_id=doc.id,
        ))
        n += 1
    return n


